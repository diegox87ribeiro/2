object DividendHistoryEngine {

    private val shortMonthsPt = listOf(
        "Jan", "Fev", "Mar", "Abr", "Mai", "Jun",
        "Jul", "Ago", "Set", "Out", "Nov", "Dez"
    )

    fun currentYmd(): Triple<Int, Int, Int> {
        val cal = Calendar.getInstance()
        return Triple(
            cal.get(Calendar.YEAR),
            cal.get(Calendar.MONTH) + 1,
            cal.get(Calendar.DAY_OF_MONTH)
        )
    }

    fun parseDateToYmd(raw: String): Triple<Int, Int, Int>? {
        val clean = raw.trim()
        if (clean.isBlank()) return null
        val slash = clean.split("/")
        if (slash.size == 3) {
            val d = slash[0].toIntOrNull()
            val m = slash[1].toIntOrNull()
            val y = slash[2].toIntOrNull()
            if (d != null && m != null && y != null && d in 1..31 && m in 1..12 && y in 1990..2100) {
                return Triple(y, m, d)
            }
        }
        val dash = clean.split("-")
        if (dash.size == 3) {
            val y = dash[0].toIntOrNull()
            val m = dash[1].toIntOrNull()
            val d = dash[2].take(2).toIntOrNull()
            if (d != null && m != null && y != null && d in 1..31 && m in 1..12 && y in 1990..2100) {
                return Triple(y, m, d)
            }
        }
        return null
    }

    fun ymdToInt(year: Int, month1Based: Int, day: Int): Int =
        year * 10000 + month1Based * 100 + day

    fun formatDateBr(day: Int, month1Based: Int, year: Int): String =
        String.format(Locale.US, "%02d/%02d/%04d", day.coerceIn(1, 31), month1Based.coerceIn(1, 12), year)

    fun addDaysToYmd(year: Int, month1Based: Int, day: Int, deltaDays: Int): Triple<Int, Int, Int> {
        val cal = Calendar.getInstance().apply {
            set(Calendar.YEAR, year)
            set(Calendar.MONTH, month1Based - 1)
            set(Calendar.DAY_OF_MONTH, day)
            add(Calendar.DAY_OF_MONTH, deltaDays)
        }
        return Triple(cal.get(Calendar.YEAR), cal.get(Calendar.MONTH) + 1, cal.get(Calendar.DAY_OF_MONTH))
    }

    fun addMonthsToYm(year: Int, month1Based: Int, deltaMonths: Int): Pair<Int, Int> {
        val totalMonths = (year * 12 + (month1Based - 1)) + deltaMonths
        val nextYear = Math.floorDiv(totalMonths, 12)
        val nextMonth1Based = Math.floorMod(totalMonths, 12) + 1
        return nextYear to nextMonth1Based
    }

    fun daysInMonth(year: Int, month1Based: Int): Int {
        val cal = Calendar.getInstance().apply {
            set(Calendar.YEAR, year)
            set(Calendar.MONTH, (month1Based - 1).coerceIn(0, 11))
            set(Calendar.DAY_OF_MONTH, 1)
        }
        return cal.getActualMaximum(Calendar.DAY_OF_MONTH)
    }

    fun buildDedupKey(
        ticker: String,
        eventType: DividendEventType,
        exDate: String,
        paymentDate: String,
        sourceReference: String = ""
    ): String {
        val cleanTicker = ticker.trim().uppercase(Locale.ROOT)
        val cleanEx = exDate.trim()
        val cleanPay = paymentDate.trim()
        val cleanRef = sourceReference.trim().uppercase(Locale.ROOT)
        return "$cleanTicker|${eventType.name}|$cleanEx|$cleanPay|$cleanRef"
    }

    /**
     * Gera o snapshot consolidado do Histórico de Proventos:
     * - Eventos persistidos (RECEIVED, CONFIRMED, PROJECTED manual, CANCELLED)
     * - Projeções automáticas (PROJECTED) geradas EXCLUSIVAMENTE para ativos com isCyclical == true
     * - Garante exclusividade mútua por (ticker, ano, mês): jamais gera PROJETADO quando já existe
     *   CONFIRMADO ou RECEBIDO no mesmo ciclo.
     * - Calcula KPIs totalmente independentes sem jamais somar projetado/confirmado em recebido.
     */
    fun buildSnapshot(
        persistedEvents: List<DividendEventEntity>,
        realPositions: List<PortfolioItemView>,
        marketAssets: List<MarketAsset>,
        liveQuotesByTicker: Map<String, LiveMarketQuote>,
        filter: DividendFilterState,
        referenceYmd: Triple<Int, Int, Int> = currentYmd(),
        projectionHorizonMonths: Int = 6
    ): DividendHistorySnapshot {
        val (refYear, refMonth, refDay) = referenceYmd
        val refYmdInt = ymdToInt(refYear, refMonth, refDay)

        val positionsByTicker = realPositions
            .filter { it.portfolioType == PortfolioType.REAL && it.ticker.isNotBlank() }
            .associateBy { it.ticker.trim().uppercase(Locale.ROOT) }
        val catalogByTicker = marketAssets.associateBy { it.ticker.trim().uppercase(Locale.ROOT) }

        val activePersisted = persistedEvents.filter { !it.isDeleted }

        // Conjunto de (ticker, year, month1Based) já ocupados por eventos persistidos ativos não-cancelados
        val occupiedTickerMonths = mutableSetOf<Triple<String, Int, Int>>()

        val persistedDisplay = activePersisted.map { entity ->
            val ticker = entity.assetTicker.trim().uppercase(Locale.ROOT)
            val pos = positionsByTicker[ticker]
            val cat = catalogByTicker[ticker]
            val status = DividendStatus.fromCode(entity.status)
            val type = DividendEventType.fromCode(entity.eventType)
            val parsedDate = parseDateToYmd(entity.paymentDate)
                ?: parseDateToYmd(entity.exDate)
                ?: referenceYmd
            val (y, m, d) = parsedDate
            if (status != DividendStatus.CANCELLED) {
                occupiedTickerMonths.add(Triple(ticker, y, m))
            }
            val computedTotal = if (entity.totalAmount > 0.0) {
                entity.totalAmount
            } else {
                entity.unitAmount * entity.quantityReference.coerceAtLeast(1.0)
            }
            DividendDisplayEvent(
                id = entity.id,
                isAutoGeneratedProjection = false,
                assetTicker = ticker,
                assetName = pos?.name ?: cat?.name ?: ticker,
                assetClass = pos?.assetClass ?: cat?.assetClass,
                isAssetInPortfolio = pos != null,
                eventType = type,
                status = status,
                exDate = entity.exDate,
                paymentDate = entity.paymentDate.ifBlank { formatDateBr(d, m, y) },
                sortYmd = ymdToInt(y, m, d),
                year = y,
                monthIndex = (m - 1).coerceIn(0, 11),
                unitAmount = entity.unitAmount,
                quantityReference = entity.quantityReference,
                totalAmount = computedTotal,
                source = entity.source.ifBlank { "Manual" },
                sourceReference = entity.sourceReference,
                isRecurring = entity.isRecurring || (pos?.isCyclical == true),
                estimated = entity.estimated || status == DividendStatus.PROJECTED,
                userEdited = entity.userEdited,
                syncDivergenceNote = entity.syncDivergenceNote,
                notes = entity.notes,
                legacyOperationId = entity.legacyOperationId
            )
        }

        // Gera projeções automáticas SOMENTE para ativos ativos na carteira marcados como recorrentes (isCyclical == true)
        val autoProjected = mutableListOf<DividendDisplayEvent>()
        var syntheticId = -1L

        val receivedHistoryByTicker = persistedDisplay
            .filter { it.status == DividendStatus.RECEIVED && it.totalAmount > 0.0 }
            .groupBy { it.assetTicker }

        positionsByTicker.values
            .filter { it.quantity > 0.0 && it.isCyclical }
            .sortedBy { it.ticker }
            .forEach { pos ->
                val ticker = pos.ticker.trim().uppercase(Locale.ROOT)
                val cat = catalogByTicker[ticker]
                val live = liveQuotesByTicker[ticker]
                val basePrice = when {
                    pos.hasMarketPrice && pos.currentPrice > 0.0 -> pos.currentPrice
                    live != null && live.price > 0.0 -> live.price
                    pos.averagePrice > 0.0 -> pos.averagePrice
                    cat != null && cat.price > 0.0 -> cat.price
                    else -> 0.0
                }
                val estimatedDy = live?.dividendYield12m?.takeIf { it > 0.0 }
                    ?: cat?.dy12m?.takeIf { it > 0.0 }
                    ?: 0.0

                // Prioriza histórico recente/último dividendo real; se ausente, usa DY mensal estimado
                val historicalUnitAvg = receivedHistoryByTicker[ticker]
                    ?.take(3)
                    ?.mapNotNull { ev ->
                        when {
                            ev.unitAmount > 0.0 && ev.quantityReference > 1.0 -> ev.unitAmount
                            ev.totalAmount > 0.0 && pos.quantity > 0.0 -> ev.totalAmount / pos.quantity
                            else -> null
                        }
                    }
                    ?.takeIf { it.isNotEmpty() }
                    ?.average()

                val perUnitMonthly = when {
                    live?.lastDividendBrl != null && live.lastDividendBrl > 0.0 -> live.lastDividendBrl
                    historicalUnitAvg != null && historicalUnitAvg > 0.0 -> historicalUnitAvg
                    estimatedDy > 0.0 && basePrice > 0.0 -> (basePrice * (estimatedDy / 100.0)) / 12.0
                    else -> 0.0
                }

                if (perUnitMonthly <= 0.0) return@forEach

                val totalMonthly = perUnitMonthly * pos.quantity
                val exDay = pos.dataComDay?.takeIf { it in 1..31 }
                    ?: live?.dataComDay?.takeIf { it in 1..31 }
                    ?: cat?.dataComDay?.takeIf { it in 1..31 }
                    ?: 10
                val payDay = live?.paymentDay?.takeIf { it in 1..31 }
                    ?: ((exDay + 7).coerceAtMost(28))

                val eventType = DividendEventType.infer(pos.assetClass, "")

                for (offset in 0 until projectionHorizonMonths) {
                    val (projYear, projMonth) = addMonthsToYm(refYear, refMonth, offset)
                    val maxDay = daysInMonth(projYear, projMonth)
                    val clampedPayDay = payDay.coerceAtMost(maxDay)
                    val clampedExDay = exDay.coerceAtMost(maxDay)
                    val projYmdInt = ymdToInt(projYear, projMonth, clampedPayDay)

                    // Projeções são sempre futuras ou do mês corrente ainda não pago/confirmado
                    if (offset == 0 && projYmdInt < refYmdInt) continue
                    // Garante exclusividade mútua: nunca duplica mês que já tem RECEBIDO, CONFIRMADO ou PROJETADO manual
                    if (Triple(ticker, projYear, projMonth) in occupiedTickerMonths) continue

                    autoProjected.add(
                        DividendDisplayEvent(
                            id = syntheticId--,
                            isAutoGeneratedProjection = true,
                            assetTicker = ticker,
                            assetName = pos.name,
                            assetClass = pos.assetClass,
                            isAssetInPortfolio = true,
                            eventType = eventType,
                            status = DividendStatus.PROJECTED,
                            exDate = formatDateBr(clampedExDay, projMonth, projYear),
                            paymentDate = formatDateBr(clampedPayDay, projMonth, projYear),
                            sortYmd = projYmdInt,
                            year = projYear,
                            monthIndex = projMonth - 1,
                            unitAmount = perUnitMonthly,
                            quantityReference = pos.quantity,
                            totalAmount = totalMonthly,
                            source = "Projeção Recorrente",
                            sourceReference = "auto_proj_${ticker}_${projYear}_${projMonth}",
                            isRecurring = true,
                            estimated = true,
                            userEdited = false,
                            syncDivergenceNote = "",
                            notes = "Estimativa automática baseada na recorrência do ativo",
                            legacyOperationId = null
                        )
                    )
                }
            }

        val allCombined = persistedDisplay + autoProjected

        // Tickers disponíveis (inclui ativos com apenas dividendos cadastrados)
        val allTickers = (positionsByTicker.keys + allCombined.map { it.assetTicker })
            .filter { it.isNotBlank() }
            .distinct()
            .sorted()

        val dividendOnlyTickers = persistedDisplay
            .map { it.assetTicker }
            .filter { it.isNotBlank() && it !in positionsByTicker }
            .toSet()

        // Janela de datas do filtro de período
        val (minYmd, maxYmd) = resolvePeriodBounds(filter, referenceYmd)

        val searchClean = filter.searchQuery.trim().uppercase(Locale.ROOT)
        val filtered = allCombined.filter { ev ->
            if (!filter.showCancelled && ev.status == DividendStatus.CANCELLED) return@filter false
            if (filter.selectedStatus != null && ev.status != filter.selectedStatus) return@filter false
            if (filter.selectedType != null && ev.eventType != filter.selectedType) return@filter false
            if (!filter.selectedTicker.isNullOrBlank() &&
                !ev.assetTicker.equals(filter.selectedTicker.trim(), ignoreCase = true)
            ) return@filter false
            if (searchClean.isNotBlank()) {
                val matchesSearch = ev.assetTicker.contains(searchClean) ||
                    ev.assetName.uppercase(Locale.ROOT).contains(searchClean) ||
                    ev.notes.uppercase(Locale.ROOT).contains(searchClean)
                if (!matchesSearch) return@filter false
            }
            if (minYmd != null && ev.sortYmd < minYmd) return@filter false
            if (maxYmd != null && ev.sortYmd > maxYmd) return@filter false
            true
        }

        val sorted = sortEvents(filtered, filter.sortColumn, filter.sortAscending)

        // KPIs estritamente independentes (nunca somam projetado/confirmado como dinheiro recebido)
        val receivedEvents = sorted.filter { it.status == DividendStatus.RECEIVED }
        val confirmedEvents = sorted.filter { it.status == DividendStatus.CONFIRMED }
        val projectedEvents = sorted.filter { it.status == DividendStatus.PROJECTED }

        val totalReceived = receivedEvents.sumOf { it.totalAmount }
        val totalConfirmed = confirmedEvents.sumOf { it.totalAmount }
        val totalProjected = projectedEvents.sumOf { it.totalAmount }

        val distinctReceivedMonths = receivedEvents
            .map { it.year * 12 + it.monthIndex }
            .distinct()
            .size
        val monthlyAvgReceived = if (distinctReceivedMonths > 0) {
            totalReceived / distinctReceivedMonths.toDouble()
        } else {
            0.0
        }

        val upcomingConfirmed = confirmedEvents
            .filter { it.sortYmd >= refYmdInt }
            .minByOrNull { it.sortYmd }
            ?: confirmedEvents.minByOrNull { it.sortYmd }
        val upcomingProjected = projectedEvents
            .filter { it.sortYmd >= refYmdInt }
            .minByOrNull { it.sortYmd }
        val nextExpected = upcomingConfirmed ?: upcomingProjected

        val largestReceived = receivedEvents.maxByOrNull { it.totalAmount }

        val monthlySeries = buildThreeSeriesTimeline(
            events = sorted.filter { it.status != DividendStatus.CANCELLED },
            filter = filter,
            referenceYmd = referenceYmd
        )

        return DividendHistorySnapshot(
            filteredEvents = sorted,
            allAvailableTickers = allTickers,
            dividendOnlyTickers = dividendOnlyTickers,
            totalReceivedBrl = totalReceived,
            totalConfirmedBrl = totalConfirmed,
            totalProjectedBrl = totalProjected,
            monthlyAverageReceivedBrl = monthlyAvgReceived,
            receivedPaymentsCount = receivedEvents.size,
            confirmedPaymentsCount = confirmedEvents.size,
            projectedPaymentsCount = projectedEvents.size,
            nextExpectedPayment = nextExpected,
            largestReceivedPayment = largestReceived,
            monthlySeries = monthlySeries
        )
    }

    private fun resolvePeriodBounds(
        filter: DividendFilterState,
        referenceYmd: Triple<Int, Int, Int>
    ): Pair<Int?, Int?> {
        val (refYear, refMonth, refDay) = referenceYmd
        // Permite exibir confirmados/projetados futuros nos próximos 6 meses nos filtros relativos
        val (futureY, futureM) = addMonthsToYm(refYear, refMonth, 6)
        val futureMaxYmd = ymdToInt(futureY, futureM, daysInMonth(futureY, futureM))

        return when (filter.period) {
            DividendPeriodFilter.LAST_30D -> {
                val (sy, sm, sd) = addDaysToYmd(refYear, refMonth, refDay, -30)
                ymdToInt(sy, sm, sd) to futureMaxYmd
            }
            DividendPeriodFilter.LAST_90D -> {
                val (sy, sm, sd) = addDaysToYmd(refYear, refMonth, refDay, -90)
                ymdToInt(sy, sm, sd) to futureMaxYmd
            }
            DividendPeriodFilter.LAST_6M -> {
                val (sy, sm) = addMonthsToYm(refYear, refMonth, -5)
                ymdToInt(sy, sm, 1) to futureMaxYmd
            }
            DividendPeriodFilter.LAST_12M -> {
                val (sy, sm) = addMonthsToYm(refYear, refMonth, -11)
                ymdToInt(sy, sm, 1) to futureMaxYmd
            }
            DividendPeriodFilter.CURRENT_YEAR -> {
                ymdToInt(refYear, 1, 1) to ymdToInt(refYear, 12, 31)
            }
            DividendPeriodFilter.PREVIOUS_YEAR -> {
                ymdToInt(refYear - 1, 1, 1) to ymdToInt(refYear - 1, 12, 31)
            }
            DividendPeriodFilter.ALL -> null to null
            DividendPeriodFilter.CUSTOM -> {
                val start = parseDateToYmd(filter.customStartDate)?.let { (y, m, d) -> ymdToInt(y, m, d) }
                val end = parseDateToYmd(filter.customEndDate)?.let { (y, m, d) -> ymdToInt(y, m, d) }
                start to end
            }
        }
    }

    private fun sortEvents(
        events: List<DividendDisplayEvent>,
        column: DividendSortColumn,
        ascending: Boolean
    ): List<DividendDisplayEvent> {
        val comparator = when (column) {
            DividendSortColumn.PAYMENT_DATE -> compareBy<DividendDisplayEvent> { it.sortYmd }.thenBy { it.assetTicker }
            DividendSortColumn.EX_DATE -> compareBy<DividendDisplayEvent> {
                parseDateToYmd(it.exDate)?.let { (y, m, d) -> ymdToInt(y, m, d) } ?: it.sortYmd
            }.thenBy { it.assetTicker }
            DividendSortColumn.TICKER -> compareBy<DividendDisplayEvent> { it.assetTicker }.thenByDescending { it.sortYmd }
            DividendSortColumn.TYPE -> compareBy<DividendDisplayEvent> { it.eventType.label }.thenByDescending { it.sortYmd }
            DividendSortColumn.UNIT_AMOUNT -> compareBy<DividendDisplayEvent> { it.unitAmount }
            DividendSortColumn.QUANTITY -> compareBy<DividendDisplayEvent> { it.quantityReference }
            DividendSortColumn.TOTAL_AMOUNT -> compareBy<DividendDisplayEvent> { it.totalAmount }
            DividendSortColumn.STATUS -> compareBy<DividendDisplayEvent> { it.status.ordinal }.thenByDescending { it.sortYmd }
        }
        return if (ascending) events.sortedWith(comparator) else events.sortedWith(comparator.reversed())
    }

    private fun buildThreeSeriesTimeline(
        events: List<DividendDisplayEvent>,
        filter: DividendFilterState,
        referenceYmd: Triple<Int, Int, Int>
    ): List<MonthlyThreeSeriesPoint> {
        val (refYear, refMonth, _) = referenceYmd
        val currentYmKey = refYear * 12 + (refMonth - 1)

        val buckets = mutableMapOf<Int, Triple<Double, Double, Double>>()
        events.forEach { ev ->
            val key = ev.year * 12 + ev.monthIndex
            val cur = buckets[key] ?: Triple(0.0, 0.0, 0.0)
            buckets[key] = when (ev.status) {
                DividendStatus.RECEIVED -> Triple(cur.first + ev.totalAmount, cur.second, cur.third)
                DividendStatus.CONFIRMED -> Triple(cur.first, cur.second + ev.totalAmount, cur.third)
                DividendStatus.PROJECTED -> Triple(cur.first, cur.second, cur.third + ev.totalAmount)
                DividendStatus.CANCELLED -> cur
            }
        }

        val monthKeys: List<Int> = when (filter.period) {
            DividendPeriodFilter.CURRENT_YEAR -> (0..11).map { refYear * 12 + it }
            DividendPeriodFilter.PREVIOUS_YEAR -> (0..11).map { (refYear - 1) * 12 + it }
            else -> {
                // Exibe últimos 6..9 meses + meses futuros presentes (até 12 barras limpas)
                val minBucket = buckets.keys.minOrNull()
                val maxBucket = buckets.keys.maxOrNull()
                val startKey = when {
                    minBucket != null && maxBucket != null && (maxBucket - minBucket) <= 13 -> minBucket
                    else -> max(minBucket ?: (currentYmKey - 7), currentYmKey - 8)
                }
                val endKey = max(maxBucket ?: (currentYmKey + 3), currentYmKey + 3)
                    .coerceAtMost(startKey + 13)
                (startKey..endKey).toList()
            }
        }

        return monthKeys.map { key ->
            val y = Math.floorDiv(key, 12)
            val mIdx = Math.floorMod(key, 12)
            val vals = buckets[key] ?: Triple(0.0, 0.0, 0.0)
            val shortYear = String.format(Locale.US, "%02d", y % 100)
            MonthlyThreeSeriesPoint(
                year = y,
                monthIndex = mIdx,
                label = "${shortMonthsPt[mIdx]}/$shortYear",
                receivedBrl = vals.first,
                confirmedBrl = vals.second,
                projectedBrl = vals.third,
                isFutureMonth = key > currentYmKey
            )
        }
    }

    /**
     * Constrói candidatos CONFIRMADOS a partir de cotações reais com dados verificados de dividendo.
     * Nunca fabrica dividendos se lastDividendBrl <= 0 ou se faltarem datas válidas.
     */
    fun buildSyncCandidatesFromQuotes(
        realPositions: List<PortfolioItemView>,
        quotesByTicker: Map<String, LiveMarketQuote>,
        referenceYmd: Triple<Int, Int, Int> = currentYmd()
    ): List<DividendSyncCandidate> {
        val (refYear, refMonth, _) = referenceYmd
        return realPositions
            .filter { it.portfolioType == PortfolioType.REAL && it.quantity > 0.0 }
            .mapNotNull { pos ->
                val ticker = pos.ticker.trim().uppercase(Locale.ROOT)
                val quote = quotesByTicker[ticker] ?: return@mapNotNull null
                val unitDiv = quote.lastDividendBrl?.takeIf { it > 0.0 } ?: return@mapNotNull null
                val exDay = quote.dataComDay?.takeIf { it in 1..31 }
                val payDay = quote.paymentDay?.takeIf { it in 1..31 }
                if (exDay == null && payDay == null) return@mapNotNull null

                val maxDay = daysInMonth(refYear, refMonth)
                val resolvedExDay = (exDay ?: (payDay!! - 5).coerceAtLeast(1)).coerceAtMost(maxDay)
                val resolvedPayDay = (payDay ?: (exDay!! + 7).coerceAtMost(maxDay)).coerceAtMost(maxDay)
                val exDate = formatDateBr(resolvedExDay, refMonth, refYear)
                val paymentDate = formatDateBr(resolvedPayDay, refMonth, refYear)
                val type = DividendEventType.infer(pos.assetClass, "")
                val sourceRef = "SYNC_${ticker}_${refYear}_${String.format(Locale.US, "%02d", refMonth)}"
                val dedupKey = buildDedupKey(ticker, type, exDate, paymentDate, sourceRef)

                DividendSyncCandidate(
                    ticker = ticker,
                    eventType = type,
                    exDate = exDate,
                    paymentDate = paymentDate,
                    unitAmount = unitDiv,
                    quantityReference = pos.quantity,
                    totalAmount = unitDiv * pos.quantity,
                    source = "AutoSync • ${quote.primarySourceLabel}",
                    sourceReference = sourceRef,
                    dedupKey = dedupKey,
                    isRecurring = pos.isCyclical
                )
            }
    }

    /**
     * Exporta os proventos atualmente filtrados em CSV UTF-8 (separador ';', padrão Excel PT-BR).
     */
    fun exportFilteredCsv(events: List<DividendDisplayEvent>): String {
        val sb = StringBuilder()
        sb.appendLine("Data-Com;Data Pagamento;Ativo;Tipo;Valor por Cota;Quantidade;Valor Total;Status;Fonte;Observacoes")
        events.forEach { ev ->
            val safeNotes = ev.notes.replace(";", ",").replace("\n", " ").trim()
            val safeSource = ev.source.replace(";", ",").trim()
            sb.appendLine(
                listOf(
                    ev.exDate.ifBlank { "-" },
                    ev.paymentDate,
                    ev.assetTicker,
                    ev.eventType.label,
                    String.format(Locale("pt", "BR"), "%.4f", ev.unitAmount),
                    String.format(Locale("pt", "BR"), "%.2f", ev.quantityReference),
                    String.format(Locale("pt", "BR"), "%.2f", ev.totalAmount),
                    ev.status.label,
                    safeSource,
                    safeNotes
                ).joinToString(";")
            )
        }
        return sb.toString()
    }

    /**
     * Recalcula quantidade e preço médio ponderado de uma posição com base nas operações
     * de COMPRA e VENDA em ordem cronológica.
     * - COMPRA atualiza preço médio ponderado.
     * - VENDA reduz quantidade mantendo o preço médio.
     * - Se não houver operações de compra/venda, preserva os valores atuais da posição.
     */
    fun recalculatePositionFromOperations(
        existingPosition: PortfolioPositionEntity?,
        operations: List<PortfolioOperationEntity>
    ): RecalculatedPositionResult {
        val tradeOps = operations
            .filter {
                it.operationType.equals(OperationType.COMPRA.name, ignoreCase = true) ||
                    it.operationType.equals(OperationType.VENDA.name, ignoreCase = true)
            }
            .sortedWith(
                compareBy<PortfolioOperationEntity> { op ->
                    parseDateToYmd(op.dateIso)?.let { (y, m, d) -> ymdToInt(y, m, d) } ?: Int.MAX_VALUE
                }.thenBy { it.createdAt }.thenBy { it.id }
            )

        if (tradeOps.isEmpty()) {
            return RecalculatedPositionResult(
                quantity = existingPosition?.quantity ?: 0.0,
                averagePrice = existingPosition?.averagePrice ?: 0.0,
                hadBuyOrSellOperations = false
            )
        }

        var qty = 0.0
        var avgPrice = 0.0

        tradeOps.forEach { op ->
            val opQty = op.quantity.coerceAtLeast(0.0)
            val opPrice = op.unitPrice.coerceAtLeast(0.0)
            if (op.operationType.equals(OperationType.COMPRA.name, ignoreCase = true)) {
                val totalCost = (qty * avgPrice) + (opQty * opPrice)
                val newQty = qty + opQty
                avgPrice = if (newQty > 0.0) totalCost / newQty else 0.0
                qty = newQty
            } else if (op.operationType.equals(OperationType.VENDA.name, ignoreCase = true)) {
                qty = (qty - opQty).coerceAtLeast(0.0)
                if (qty <= 0.00001) {
                    qty = 0.0
                    avgPrice = 0.0
                }
            }
        }

        return RecalculatedPositionResult(
            quantity = qty,
            averagePrice = if (abs(avgPrice) < 0.00001) 0.0 else avgPrice,
            hadBuyOrSellOperations = true
        )
    }
