enum class DividendStatus(val label: String, val badgeText: String) {
    RECEIVED("Recebido", "Recebido"),
    CONFIRMED("Confirmado", "Confirmado"),
    PROJECTED("Projetado", "Projetado"),
    CANCELLED("Cancelado", "Cancelado");

    companion object {
        fun fromCode(code: String?): DividendStatus {
            return entries.firstOrNull { it.name.equals(code?.trim(), ignoreCase = true) } ?: RECEIVED
        }
    }
}

enum class DividendEventType(val label: String) {
    DIVIDENDO("Dividendos"),
    JCP("JCP"),
    RENDIMENTO_FII("Rendimento FII"),
    RENDIMENTO_FIAGRO("Rendimento FIAGRO"),
    AMORTIZACAO("Amortização"),
    OUTROS("Outros");

    companion object {
        fun fromCode(code: String?): DividendEventType {
            return entries.firstOrNull { it.name.equals(code?.trim(), ignoreCase = true) } ?: DIVIDENDO
        }

        fun infer(assetClass: AssetClass?, notes: String): DividendEventType {
            val upper = notes.uppercase(Locale.ROOT)
            return when {
                upper.contains("JCP") || upper.contains("JUROS") -> JCP
                upper.contains("AMORT") -> AMORTIZACAO
                upper.contains("FIAGRO") || assetClass == AssetClass.FIAGRO -> RENDIMENTO_FIAGRO
                upper.contains("FII") || upper.contains("REND") || assetClass == AssetClass.FII -> RENDIMENTO_FII
                upper.contains("OUTRO") || upper.contains("BONIF") -> OUTROS
                else -> DIVIDENDO
            }
        }
    }
}

