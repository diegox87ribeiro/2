data class DividendFilterState(
    val period: DividendPeriodFilter = DividendPeriodFilter.LAST_12M,
    val customStartDate: String = "",
    val customEndDate: String = "",
    val selectedTicker: String? = null,
    val searchQuery: String = "",
    val selectedStatus: DividendStatus? = null,
    val selectedType: DividendEventType? = null,
    val showCancelled: Boolean = false,
    val sortColumn: DividendSortColumn = DividendSortColumn.PAYMENT_DATE,
    val sortAscending: Boolean = false
) {
    val isDefault: Boolean
        get() = period == DividendPeriodFilter.LAST_12M &&
            customStartDate.isBlank() &&
            customEndDate.isBlank() &&
            selectedTicker == null &&
            searchQuery.isBlank() &&
            selectedStatus == null &&
            selectedType == null &&
            !showCancelled &&
            sortColumn == DividendSortColumn.PAYMENT_DATE &&
            !sortAscending
}

