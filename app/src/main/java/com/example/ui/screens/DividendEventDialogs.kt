data class DividendEventFormDraft(
    val id: Long? = null,
    val ticker: String = "",
    val eventType: DividendEventType = DividendEventType.DIVIDENDO,
    val status: DividendStatus = DividendStatus.RECEIVED,
    val exDate: String = "",
    val paymentDate: String = "",
    val unitAmount: Double = 0.0,
    val quantityReference: Double = 1.0,
    val totalAmount: Double = 0.0,
    val source: String = "Manual",
    val notes: String = "",
    val isRecurring: Boolean = false
)

fun DividendDisplayEvent.toEditDraft(): DividendEventFormDraft = DividendEventFormDraft(
    id = if (isAutoGeneratedProjection) null else id,
    ticker = assetTicker,
    eventType = eventType,
    status = status,
    exDate = exDate,
    paymentDate = paymentDate,
    unitAmount = unitAmount,
    quantityReference = quantityReference,
    totalAmount = totalAmount,
    source = source,
    notes = notes,
    isRecurring = isRecurring
)

@OptIn(ExperimentalLayoutApi::class)
@Composable
fun DividendEventFormDialog(
    draft: DividendEventFormDraft,
    realPositions: List<PortfolioItemView>,
    onDismiss: () -> Unit,
    onSave: (
        id: Long?,
        ticker: String,
        eventType: DividendEventType,
        status: DividendStatus,
        exDate: String,
        paymentDate: String,
        unitAmount: Double,
        quantityReference: Double,
        totalAmount: Double,
        source: String,
        notes: String,
        isRecurring: Boolean
    ) -> Unit
) {
    val isEditing = draft.id != null && draft.id > 0L
    val todayFormatted = remember {
        val (y, m, d) = DividendHistoryEngine.currentYmd()
        DividendHistoryEngine.formatDateBr(d, m, y)
    }

    var ticker by remember(draft) { mutableStateOf(draft.ticker) }
    var eventType by remember(draft) { mutableStateOf(draft.eventType) }
    var status by remember(draft) { mutableStateOf(draft.status) }
    var exDate by remember(draft) { mutableStateOf(draft.exDate) }
    var paymentDate by remember(draft) { mutableStateOf(draft.paymentDate.ifBlank { todayFormatted }) }
    var unitAmountText by remember(draft) {
        mutableStateOf(
            if (draft.unitAmount > 0.0) String.format(Locale("pt", "BR"), "%.4f", draft.unitAmount) else ""
        )
    }
    var qtyText by remember(draft) {
        mutableStateOf(
            if (draft.quantityReference > 0.0) String.format(Locale("pt", "BR"), "%.2f", draft.quantityReference) else "1"
        )
    }
    var totalAmountText by remember(draft) {
        mutableStateOf(
            if (draft.totalAmount > 0.0) String.format(Locale("pt", "BR"), "%.2f", draft.totalAmount) else ""
        )
    }
    var source by remember(draft) { mutableStateOf(draft.source.ifBlank { "Manual" }) }
    var notes by remember(draft) { mutableStateOf(draft.notes) }
    var isRecurring by remember(draft) { mutableStateOf(draft.isRecurring) }

    val parsedUnit = parseBrlDecimal(unitAmountText) ?: 0.0
    val parsedQty = parseBrlDecimal(qtyText) ?: 0.0
    val parsedTotal = parseBrlDecimal(totalAmountText) ?: 0.0
    val effectiveTotal = if (parsedTotal > 0.0) parsedTotal else parsedUnit * parsedQty

    val isValid = ticker.trim().length >= 3 &&
        effectiveTotal > 0.0 &&
        DividendHistoryEngine.parseDateToYmd(paymentDate) != null

    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = DarkPremiumCard,
        title = {
            Text(
                text = if (isEditing) "Editar Provento • ${draft.ticker}" else "Novo Evento de Provento",
                color = PremiumTextPrimary,
                fontWeight = FontWeight.Bold
            )
        },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 460.dp)
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                OutlinedTextField(
                    value = ticker,
                    onValueChange = { raw ->
                        val upper = raw.uppercase(Locale.ROOT)
                        ticker = upper
                        val match = realPositions.firstOrNull { it.ticker.equals(upper.trim(), ignoreCase = true) }
                        if (match != null && !isEditing) {
                            qtyText = String.format(Locale("pt", "BR"), "%.2f", match.quantity)
                            isRecurring = match.isCyclical
                            eventType = DividendEventType.infer(match.assetClass, "")
                        }
                    },
                    label = { Text("Ticker do Ativo (editável)") },
                    supportingText = { Text("Você pode alterar livremente o ticker, inclusive de ativos só com dividendos.") },
                    singleLine = true,
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("dividend_form_ticker_input")
                )

                Text("Status do Provento (mutuamente exclusivo)", style = MaterialTheme.typography.labelMedium, color = PremiumTextSecondary)
                FlowRow(
                    horizontalArrangement = Arrangement.spacedBy(6.dp),
                    verticalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    DividendStatus.entries.forEach { st ->
                        val accent = statusColor(st)
                        FilterChip(
                            selected = status == st,
                            onClick = { status = st },
                            label = { Text(st.label, style = MaterialTheme.typography.labelSmall) },
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = accent.copy(alpha = 0.22f),
                                selectedLabelColor = accent
                            ),
                            modifier = Modifier.testTag("dividend_form_status_${st.name}")
                        )
                    }
                }

                Text("Tipo de Provento", style = MaterialTheme.typography.labelMedium, color = PremiumTextSecondary)
                FlowRow(
                    horizontalArrangement = Arrangement.spacedBy(6.dp),
                    verticalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    DividendEventType.entries.forEach { tp ->
                        FilterChip(
                            selected = eventType == tp,
                            onClick = { eventType = tp },
                            label = { Text(tp.label, style = MaterialTheme.typography.labelSmall) },
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = TechBluePrimary.copy(alpha = 0.25f),
                                selectedLabelColor = ConfirmedBlue
                            )
                        )
                    }
                }

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedTextField(
                        value = exDate,
                        onValueChange = { exDate = it },
                        label = { Text("Data-Com (opc.)") },
                        placeholder = { Text("dd/MM/aaaa") },
                        singleLine = true,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("dividend_form_ex_date_input")
                    )
                    OutlinedTextField(
                        value = paymentDate,
                        onValueChange = { paymentDate = it },
                        label = { Text("Data Pgto*") },
                        placeholder = { Text("dd/MM/aaaa") },
                        singleLine = true,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("dividend_form_payment_date_input")
                    )
                }

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedTextField(
                        value = unitAmountText,
                        onValueChange = { txt ->
                            unitAmountText = txt
                            val u = parseBrlDecimal(txt) ?: 0.0
                            val q = parseBrlDecimal(qtyText) ?: 0.0
                            if (u > 0.0 && q > 0.0) {
                                totalAmountText = String.format(Locale("pt", "BR"), "%.2f", u * q)
                            }
                        },
                        label = { Text("Valor/Cota (R$)") },
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Decimal),
                        singleLine = true,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("dividend_form_unit_input")
                    )
                    OutlinedTextField(
                        value = qtyText,
                        onValueChange = { txt ->
                            qtyText = txt
                            val u = parseBrlDecimal(unitAmountText) ?: 0.0
                            val q = parseBrlDecimal(txt) ?: 0.0
                            if (u > 0.0 && q > 0.0) {
                                totalAmountText = String.format(Locale("pt", "BR"), "%.2f", u * q)
                            }
                        },
                        label = { Text("Quantidade") },
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Decimal),
                        singleLine = true,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("dividend_form_qty_input")
                    )
                }

                OutlinedTextField(
                    value = totalAmountText,
                    onValueChange = { totalAmountText = it },
                    label = { Text("Valor Total (R$)*") },
                    supportingText = {
                        Text("Calculado: ${formatBrl(effectiveTotal)} • ajuste manualmente se necessário")
                    },
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Decimal),
                    singleLine = true,
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("dividend_form_total_input")
                )

                OutlinedTextField(
                    value = source,
                    onValueChange = { source = it },
                    label = { Text("Fonte do dado") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )

                OutlinedTextField(
                    value = notes,
                    onValueChange = { notes = it },
                    label = { Text("Observações (opcional)") },
                    modifier = Modifier.fillMaxWidth()
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text("Provento recorrente", style = MaterialTheme.typography.bodyMedium, color = PremiumTextPrimary)
                        Text(
                            "Indica pagamento periódico conforme recorrência do ativo",
                            style = MaterialTheme.typography.labelSmall,
                            color = PremiumTextSecondary
                        )
                    }
                    Switch(checked = isRecurring, onCheckedChange = { isRecurring = it })
                }
            }
        },
        confirmButton = {
            Button(
                onClick = {
                    val cleanQty = parsedQty.takeIf { it > 0.0 } ?: 1.0
                    val cleanUnit = parsedUnit.takeIf { it > 0.0 } ?: (effectiveTotal / cleanQty)
                    onSave(
                        draft.id,
                        ticker.trim().uppercase(Locale.ROOT),
                        eventType,
                        status,
                        exDate.trim(),
                        paymentDate.trim(),
                        cleanUnit,
                        cleanQty,
                        effectiveTotal,
                        source.trim().ifBlank { "Manual" },
                        notes.trim(),
                        isRecurring
                    )
                },
                enabled = isValid,
                colors = ButtonDefaults.buttonColors(
                    containerColor = ReceivedGreen,
                    contentColor = EmeraldOnPrimary
                ),
                modifier = Modifier.testTag("dividend_form_save_button")
            ) {
                Text(if (isEditing) "Salvar Alterações" else "Cadastrar Provento")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) { Text("Cancelar", color = PremiumTextSecondary) }
        }
    )
}

@Composable
fun RenameDividendTickerDialog(
    currentTicker: String,
    onDismiss: () -> Unit,
    onConfirm: (oldTicker: String, newTicker: String) -> Unit
) {
    var newTicker by remember(currentTicker) { mutableStateOf(currentTicker) }
    val cleanNew = newTicker.trim().uppercase(Locale.ROOT)
    val isValid = cleanNew.length >= 3 && !cleanNew.equals(currentTicker.trim(), ignoreCase = true)

    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = DarkPremiumCard,
        title = {
            Text(
                text = "Editar Ticker • $currentTicker",
                color = PremiumTextPrimary,
                fontWeight = FontWeight.Bold
            )
        },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text(
                    text = "Atualiza o ticker em todos os lançamentos de proventos deste ativo (mesmo sem posição cadastrada na carteira).",
                    style = MaterialTheme.typography.bodySmall,
                    color = PremiumTextSecondary
                )
                OutlinedTextField(
                    value = newTicker,
                    onValueChange = { newTicker = it.uppercase(Locale.ROOT) },
                    label = { Text("Novo Ticker (ex.: MXRF11, EGAF11)") },
                    singleLine = true,
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("rename_dividend_ticker_input")
                )
            }
        },
        confirmButton = {
            Button(
                onClick = { onConfirm(currentTicker, cleanNew) },
                enabled = isValid,
                colors = ButtonDefaults.buttonColors(containerColor = ReceivedGreen, contentColor = EmeraldOnPrimary),
                modifier = Modifier.testTag("rename_dividend_ticker_confirm")
            ) {
                Text("Atualizar Ticker")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) { Text("Cancelar", color = PremiumTextSecondary) }
        }
    )
}

