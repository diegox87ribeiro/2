@Composable
fun DividendEventDetailDialog(
    event: DividendDisplayEvent,
    relatedAuditLogs: List<FinancialAuditLogEntity>,
    onDismiss: () -> Unit,
    onEdit: () -> Unit
) {
    val dateFmt = remember { SimpleDateFormat("dd/MM/yyyy HH:mm", Locale("pt", "BR")) }
    val accent = statusColor(event.status)

    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = DarkPremiumCard,
        title = {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                Text("${event.assetTicker} • ${event.eventType.label}", color = PremiumTextPrimary, fontWeight = FontWeight.Bold)
            }
        },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 420.dp)
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                DetailRow("Status", event.status.label, accent)
                DetailRow("Data-Com", event.exDate.ifBlank { "Não informada" })
                DetailRow("Data Pagamento", event.paymentDate)
                DetailRow("Valor por Cota", formatBrl(event.unitAmount))
                DetailRow("Quantidade Ref.", String.format(Locale("pt", "BR"), "%.2f", event.quantityReference))
                DetailRow("Valor Total", formatBrl(event.totalAmount), accent)
                DetailRow("Origem / Fonte", event.source)
                DetailRow("Recorrente", if (event.isRecurring) "Sim" else "Não")
                DetailRow("Estimativa", if (event.estimated) "Sim (Projetado)" else "Não")
                if (event.notes.isNotBlank()) {
                    DetailRow("Observações", event.notes)
                }
                if (event.syncDivergenceNote.isNotBlank()) {
                    Surface(
                        shape = RoundedCornerShape(10.dp),
                        color = ProjectedAmber.copy(alpha = 0.14f),
                        border = BorderStroke(1.dp, ProjectedAmber.copy(alpha = 0.45f)),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Text(
                            text = event.syncDivergenceNote,
                            style = MaterialTheme.typography.labelSmall,
                            color = ProjectedAmber,
                            modifier = Modifier.padding(8.dp)
                        )
                    }
                }

                if (relatedAuditLogs.isNotEmpty()) {
                    Spacer(Modifier.height(6.dp))
                    HorizontalDivider(color = DarkPremiumBorder)
                    Text(
                        text = "Histórico de Alterações (${relatedAuditLogs.size})",
                        style = MaterialTheme.typography.labelLarge,
                        color = ConfirmedBlue
                    )
                    relatedAuditLogs.take(6).forEach { log ->
                        Text(
                            text = "• ${dateFmt.format(Date(log.changedAt))} [${log.actionType}] ${log.newSummary.ifBlank { log.reason }}",
                            style = MaterialTheme.typography.labelSmall,
                            color = PremiumTextSecondary
                        )
                    }
                }
            }
        },
        confirmButton = {
            Button(
                onClick = onEdit,
                colors = ButtonDefaults.buttonColors(containerColor = TechBluePrimary, contentColor = Color.White)
            ) {
                Text("Editar")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) { Text("Fechar", color = PremiumTextSecondary) }
        }
    )
}

@Composable
fun AuditAndRestoreDialog(
    auditLogs: List<FinancialAuditLogEntity>,
    onDismiss: () -> Unit,
    onRestoreAuditEntry: (Long) -> Unit
) {
    val dateFmt = remember { SimpleDateFormat("dd/MM/yyyy HH:mm", Locale("pt", "BR")) }

    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = DarkPremiumCard,
        icon = { Icon(Icons.Default.History, contentDescription = null, tint = ConfirmedBlue) },
        title = {
            Text(
                text = "Auditoria & Restauração",
                color = PremiumTextPrimary,
                fontWeight = FontWeight.Bold
            )
        },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 440.dp)
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                if (auditLogs.isEmpty()) {
                    Text(
                        text = "Nenhuma alteração, exclusão ou sincronização registrada ainda.",
                        style = MaterialTheme.typography.bodySmall,
                        color = PremiumTextSecondary
                    )
                } else {
                    Text(
                        text = "Todas as criações, edições, exclusões e sincronizações ficam auditadas. Registros excluídos podem ser restaurados com recálculo automático.",
                        style = MaterialTheme.typography.labelSmall,
                        color = PremiumTextSecondary
                    )
                    auditLogs.forEach { log ->
                        val canRestore = log.actionType == "DELETE" &&
                            (log.restorePayloadJson.isNotBlank() || log.entityType == "DIVIDEND_EVENT")
                        Surface(
                            shape = RoundedCornerShape(10.dp),
                            color = DarkPremiumCardSecondary,
                            border = BorderStroke(1.dp, DarkPremiumBorder),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Column(modifier = Modifier.padding(10.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.SpaceBetween,
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Text(
                                        text = "${log.ticker} • ${auditActionLabel(log.actionType)}",
                                        style = MaterialTheme.typography.labelLarge,
                                        color = auditActionColor(log.actionType),
                                        fontWeight = FontWeight.SemiBold
                                    )
                                    Text(
                                        text = dateFmt.format(Date(log.changedAt)),
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PremiumTextSecondary
                                    )
                                }
                                if (log.previousSummary.isNotBlank()) {
                                    Text(
                                        text = "Antes: ${log.previousSummary}",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PremiumTextSecondary
                                    )
                                }
                                if (log.newSummary.isNotBlank()) {
                                    Text(
                                        text = "Depois: ${log.newSummary}",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PremiumTextPrimary
                                    )
                                }
                                Text(
                                    text = "Origem: ${log.source} • ${log.reason}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = PremiumTextSecondary
                                )
                                if (canRestore) {
                                    OutlinedButton(
                                        onClick = { onRestoreAuditEntry(log.id) },
                                        border = BorderStroke(1.dp, ReceivedGreen.copy(alpha = 0.6f)),
                                        modifier = Modifier
                                            .heightIn(min = 48.dp)
                                            .testTag("restore_audit_button_${log.id}")
                                    ) {
                                        Icon(
                                            imageVector = Icons.Default.Restore,
                                            contentDescription = null,
                                            tint = ReceivedGreen,
                                            modifier = Modifier.size(16.dp)
                                        )
                                        Spacer(Modifier.width(6.dp))
                                        Text("Restaurar", color = ReceivedGreen)
                                    }
                                }
                            }
                        }
                    }
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text("Fechar", color = ConfirmedBlue) }
        }
    )
}

@Composable
private fun DetailRow(label: String, value: String, valueColor: Color = PremiumTextPrimary) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(label, style = MaterialTheme.typography.labelMedium, color = PremiumTextSecondary)
        Text(value, style = MaterialTheme.typography.bodySmall, color = valueColor, fontWeight = FontWeight.Medium)
    }
}

internal fun statusColor(status: DividendStatus): Color = when (status) {
    DividendStatus.RECEIVED -> ReceivedGreen
    DividendStatus.CONFIRMED -> ConfirmedBlue
    DividendStatus.PROJECTED -> ProjectedAmber
    DividendStatus.CANCELLED -> CancelledRed
}

private fun auditActionLabel(action: String): String = when (action) {
    "CREATE" -> "Cadastro"
    "UPDATE" -> "Edição"
    "STATUS_CHANGE" -> "Mudança Status"
    "RENAME_TICKER" -> "Ticker Renomeado"
    "DELETE" -> "Exclusão"
    "RESTORE" -> "Restauração"
    "AUTO_SYNC" -> "Sync Automático"
    "SYNC_DIVERGENCE" -> "Divergência Sync"
    else -> action
}

private fun auditActionColor(action: String): Color = when (action) {
    "CREATE", "RESTORE" -> ReceivedGreen
    "UPDATE", "STATUS_CHANGE", "RENAME_TICKER", "AUTO_SYNC" -> ConfirmedBlue
    "SYNC_DIVERGENCE" -> ProjectedAmber
    "DELETE" -> CancelledRed
    else -> PremiumTextPrimary
}
